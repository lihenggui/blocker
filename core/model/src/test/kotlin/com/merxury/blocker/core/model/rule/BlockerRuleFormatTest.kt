package com.merxury.blocker.core.model.rule

import com.google.common.truth.Truth.assertThat
import com.merxury.blocker.core.model.ComponentType
import com.merxury.blocker.core.model.data.ControllerType
import kotlinx.serialization.SerializationException
import kotlinx.serialization.encodeToString
import kotlinx.serialization.json.Json
import org.junit.Assert.assertThrows
import org.junit.Test

/**
 * Pins the Blocker rule backup format: one `<package>.json` per app, written by
 * ExportBlockerRulesWorker and read by ImportBlockerRuleWorker.
 *
 * [json] repeats the instance both workers get from NetworkModule.providesNetworkJson in
 * core:network, which core:rule and core:model cannot depend on. If that configuration changes,
 * update it here on purpose.
 */
class BlockerRuleFormatTest {
    private val json = Json {
        ignoreUnknownKeys = true
        prettyPrint = true
        encodeDefaults = true
        explicitNulls = false
    }

    private fun resource(name: String): String = checkNotNull(javaClass.classLoader?.getResource("blocker-rule/$name")) {
        "Missing test resource $name"
    }.readText()

    private val allEnumValuesRule = BlockerRule(
        packageName = "com.example.app",
        versionName = "1.2.3",
        versionCode = 123,
        author = "Blocker",
        description = "Generated by Blocker",
        components = mutableListOf(
            ComponentRule(
                "com.example.app",
                "com.example.app.BootReceiver",
                false,
                ComponentType.RECEIVER,
                ControllerType.IFW,
            ),
            ComponentRule(
                "com.example.app",
                "com.example.app.MainActivity",
                true,
                ComponentType.ACTIVITY,
                ControllerType.PM,
            ),
            ComponentRule(
                "com.example.app",
                "com.example.app.SyncService",
                false,
                ComponentType.SERVICE,
                ControllerType.SHIZUKU,
            ),
            ComponentRule(
                "com.example.app",
                "com.example.app.DataProvider",
                false,
                ComponentType.PROVIDER,
                ControllerType.IFW_PLUS_PM,
            ),
        ),
    )

    @Test
    fun givenGoldenFileWithEveryEnumValue_whenDecoding_thenFieldsMatch() {
        val rule = json.decodeFromString<BlockerRule>(resource("all_enum_values.json"))

        assertThat(rule).isEqualTo(allEnumValuesRule)
    }

    @Test
    fun givenKnownModel_whenEncoding_thenProducesExactlyTheGoldenText() {
        val text = json.encodeToString(allEnumValuesRule)

        assertThat(text).isEqualTo(resource("all_enum_values.json").trimEnd())
    }

    @Test
    fun givenFileWithUnknownKeys_whenDecoding_thenUnknownKeysAreIgnored() {
        val rule = json.decodeFromString<BlockerRule>(resource("unknown_keys.json"))

        assertThat(rule).isEqualTo(
            BlockerRule(
                packageName = "com.example.app",
                versionName = "2.0",
                versionCode = 20,
                author = "Someone",
                description = "Edited by hand",
                components = mutableListOf(
                    ComponentRule(
                        "com.example.app",
                        "com.example.app.Tracker",
                        false,
                        ComponentType.SERVICE,
                        ControllerType.PM,
                    ),
                ),
            ),
        )
    }

    @Test
    fun givenFileWithMissingOptionalKeys_whenDecoding_thenDefaultsApply() {
        val rule = json.decodeFromString<BlockerRule>(resource("missing_optional_keys.json"))

        assertThat(rule.packageName).isEqualTo("com.example.app")
        assertThat(rule.versionName).isEqualTo("")
        assertThat(rule.versionCode).isEqualTo(-1L)
        assertThat(rule.author).isEqualTo("Blocker")
        assertThat(rule.description).isEqualTo("Generated by Blocker")
        assertThat(rule.components).containsExactly(
            ComponentRule(
                packageName = "",
                name = "com.example.app.Tracker",
                state = true,
                type = ComponentType.RECEIVER,
                method = ControllerType.PM,
            ),
        )
    }

    @Test
    fun givenEmptyObject_whenDecoding_thenEveryFieldHasItsDefault() {
        val rule = json.decodeFromString<BlockerRule>("{}")

        assertThat(rule).isEqualTo(BlockerRule())
        assertThat(rule.packageName).isEqualTo("")
        assertThat(rule.components).isEmpty()
    }

    @Test
    fun givenExplicitNullsForNullableFields_whenDecoding_thenFieldsAreNull() {
        val rule = json.decodeFromString<BlockerRule>(resource("explicit_nulls.json"))

        assertThat(rule.packageName).isNull()
        assertThat(rule.versionName).isNull()
        assertThat(rule.versionCode).isNull()
        assertThat(rule.author).isNull()
        assertThat(rule.description).isNull()
    }

    @Test
    fun givenNullFields_whenEncoding_thenTheKeysAreOmitted() {
        val text = json.encodeToString(
            BlockerRule(
                packageName = "com.example.app",
                versionName = null,
                versionCode = null,
                author = null,
                description = null,
            ),
        )

        assertThat(text).isEqualTo(
            """
            {
                "packageName": "com.example.app",
                "components": []
            }
            """.trimIndent(),
        )
    }

    @Test
    fun givenUnknownComponentTypeName_whenDecoding_thenThrowsSerializationException() {
        val error = assertThrows(SerializationException::class.java) {
            json.decodeFromString<BlockerRule>(resource("unknown_enum_name.json"))
        }

        assertThat(error).hasMessageThat().contains("WIDGET")
        assertThat(error).hasMessageThat().contains("ComponentType")
    }

    @Test
    fun givenUnknownControllerMethodName_whenDecoding_thenThrowsSerializationException() {
        val error = assertThrows(SerializationException::class.java) {
            json.decodeFromString<BlockerRule>(resource("unknown_method_name.json"))
        }

        assertThat(error).hasMessageThat().contains("ROOT")
        assertThat(error).hasMessageThat().contains("ControllerType")
    }

    @Test
    fun givenLowercaseEnumName_whenDecoding_thenThrowsSerializationException() {
        assertThrows(SerializationException::class.java) {
            json.decodeFromString<BlockerRule>(resource("lowercase_enum_name.json"))
        }
    }

    @Test
    fun givenEveryControllerType_whenToComponentInfo_thenOnlyMatchingFlagIsBlocked() {
        fun rule(method: ControllerType) = ComponentRule(
            packageName = "p",
            name = "p.C",
            state = false,
            type = ComponentType.SERVICE,
            method = method,
        ).toComponentInfo()

        assertThat(rule(ControllerType.PM).pmBlocked).isTrue()
        assertThat(rule(ControllerType.PM).ifwBlocked).isFalse()
        assertThat(rule(ControllerType.IFW).ifwBlocked).isTrue()
        assertThat(rule(ControllerType.IFW).pmBlocked).isFalse()
        // SHIZUKU and IFW_PLUS_PM entries read back as not blocked by either flag.
        assertThat(rule(ControllerType.SHIZUKU).pmBlocked).isFalse()
        assertThat(rule(ControllerType.SHIZUKU).ifwBlocked).isFalse()
        assertThat(rule(ControllerType.IFW_PLUS_PM).pmBlocked).isFalse()
        assertThat(rule(ControllerType.IFW_PLUS_PM).ifwBlocked).isFalse()
    }
}
